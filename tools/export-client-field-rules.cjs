'use strict';
// Run after `node build`. Only move-preview hooks are exported; never run battle events in the UI.
const fs = require('fs');
const path = require('path');
const {Dex} = require('../dist/sim');
const ts = require('typescript');
const destination = process.argv[2];
if (!destination) throw new Error('Usage: node tools/export-client-field-rules.cjs <client-root>');
const hooks = ['onBasePower', 'onModifyType', 'onModifyMove', 'onAccuracy', 'onModifyPriority', 'onTryMove'];
const rows = [];
const terrains = [...Dex.terrains.all(), ...['electricterrain', 'grassyterrain', 'mistyterrain', 'psychicterrain'].map(id => ({id, name: Dex.conditions.get(id).name, condition: Dex.conditions.get(id)}))];
for (const terrain of terrains) {
	const condition = terrain.condition || {};
	const entries = [`id: ${JSON.stringify(terrain.id)}`, `name: ${JSON.stringify(terrain.name)}`];
	for (const key of hooks) {
		if (!condition[key]) continue;
		let code = condition[key].toString();
		if (terrain.id.startsWith('flowergarden')) code = code.replace(/\bstage\b/g, terrain.id.slice(-1));
		// The legacy client compiler treats spread iterables as arrays. Materialize Sets explicitly.
		const parsed = ts.createSourceFile('hook.ts', `({${code}})`, ts.ScriptTarget.Latest, true);
		const transformed = ts.transform(parsed, [context => root => {
			function visit(node) {
				if (ts.isArrayLiteralExpression(node) && node.elements.length === 1 && ts.isSpreadElement(node.elements[0])) {
					return ts.factory.createCallExpression(ts.factory.createPropertyAccessExpression(ts.factory.createIdentifier('Array'), 'from'),
						undefined, [ts.visitNode(node.elements[0].expression, visit)]);
				}
				return ts.visitEachChild(node, visit, context);
			}
			return ts.visitNode(root, visit);
		}]);
		const expression = transformed.transformed[0].statements[0].expression.expression;
		entries.push(ts.createPrinter().printNode(ts.EmitHint.Unspecified, expression.properties[0], parsed));
		transformed.dispose();
	}
	const code = entries.join(',\n');
	entries.push(`uncertain: ${JSON.stringify(/terrainChanges|terrainStack|underlyingTerrain|prevTerrain|ShortCircuitCounter|CrystalCavernCounter/.test(code))}`);
	rows.push(`{${entries.join(',\n')}}`);
}
const moveRows = [];
for (const move of Dex.moves.all()) {
	const entries = [];
	for (const key of ['onModifyType', 'onModifyMove', 'onBasePower', 'basePowerCallback']) {
		if (typeof move[key] === 'function' && /field\.(?:isTerrain|terrain|getTerrain|canSetTerrain)/.test(move[key].toString())) entries.push(move[key].toString());
	}
	if (!entries.length) continue;
	const base = {};
	for (const key of ['boosts', 'self', 'selfBoost', 'heal', 'recoil', 'drain', 'secondaries', 'volatileStatus', 'critRatio']) {
		if (move[key] !== undefined) base[key] = move[key];
	}
	entries.push(`base: ${JSON.stringify(base)}`);
	entries.push(`uncertain: ${/terrainChanges|CrystalCavernCounter|this.sample/.test(entries.join(''))}`);
	moveRows.push(`${JSON.stringify(move.id)}: {${entries.join(',\n')}}`);
}
const output = '// @ts-nocheck\n// Generated by server tools/export-client-field-rules.cjs. Do not edit by hand.\n' +
	'// Functions operate only on preview snapshots, never on the live battle.\n' +
	`const BattleFieldRules = [\n${rows.join(',\n')}\n];\n` +
	`const BattleFieldMoveRules = {${moveRows.join(',\n')}};\n` +
	`if (typeof window !== 'undefined') (window as any).BattleFieldMoveRules = BattleFieldMoveRules;\n` +
	`if (typeof window !== 'undefined') (window as any).BattleFieldRules = BattleFieldRules;\n` +
	`if (typeof require === 'function') (global as any).BattleFieldRules = BattleFieldRules;\n`;
fs.writeFileSync(path.join(destination, 'play.pokemonshowdown.com/src/battle-field-rules.ts'), output);
console.log(`Exported ${rows.length} fields and ${hooks.join(', ')}.`);
