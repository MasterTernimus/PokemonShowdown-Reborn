'use strict';

const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const inputPath = process.argv[2];
const outputPath = process.argv[3] || path.resolve(__dirname, '../data/natdex-gen8-gen9-learnsets.ts');

if (!inputPath) {
	throw new Error('Usage: node tools/generate-gen8-gen9-natdex-learnsets.js <upstream-learnsets.ts> [output.ts]');
}

const source = fs.readFileSync(inputPath, 'utf8');
const compiled = ts.transpileModule(source, {
	compilerOptions: {
		module: ts.ModuleKind.CommonJS,
		target: ts.ScriptTarget.ES2020,
	},
}).outputText;

const upstreamModule = {exports: {}};
const loadModule = new Function('exports', 'module', 'require', '__filename', '__dirname', compiled);
loadModule(upstreamModule.exports, upstreamModule, require, inputPath, path.dirname(inputPath));

const upstreamLearnsets = upstreamModule.exports.Learnsets;
if (!upstreamLearnsets || typeof upstreamLearnsets !== 'object') {
	throw new Error(`Could not load Learnsets from ${inputPath}`);
}

const generatedLearnsets = {};
for (const [species, data] of Object.entries(upstreamLearnsets)) {
	const learnset = {};
	for (const [move, sources] of Object.entries(data.learnset || {})) {
		const modernSources = sources.filter(sourceRecord => /^[89]/.test(sourceRecord));
		if (modernSources.length) learnset[move] = modernSources;
	}

	const eventData = (data.eventData || []).filter(event => event.generation === 8 || event.generation === 9);
	const encounters = (data.encounters || []).filter(event => event.generation === 8 || event.generation === 9);
	if (!Object.keys(learnset).length && !eventData.length && !encounters.length) continue;

	generatedLearnsets[species] = {learnset};
	if (eventData.length) generatedLearnsets[species].eventData = eventData;
	if (encounters.length) generatedLearnsets[species].encounters = encounters;
}

const header = `// Generated by tools/generate-gen8-gen9-natdex-learnsets.js.\n` +
	`// Source: https://github.com/smogon/pokemon-showdown/blob/master/data/learnsets.ts\n` +
	`// Contains only official Generation 8 and 9 move sources, events, and encounters.\n`;
const output = `${header}export const Gen8Gen9NatDexLearnsets: import('../sim/dex-species').LearnsetDataTable = ${
	JSON.stringify(generatedLearnsets, null, '\t')
};\n`;

fs.writeFileSync(outputPath, output);
console.log(`Wrote ${Object.keys(generatedLearnsets).length} learnsets to ${outputPath}`);
